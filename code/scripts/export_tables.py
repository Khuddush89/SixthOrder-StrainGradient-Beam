"""Export numerical tables to Markdown; no manuscript files are needed."""
from pathlib import Path
import json
ROOT = Path(__file__).resolve().parents[2]
r = json.loads((ROOT / 'code/results/results.json').read_text())
lines = ['# Numerical results', '', 'Generated by `code/scripts/export_tables.py` from `results.json`.', '',
         '## Kernel constants and exponential folds', '',
         'The optimized cone constants and folds are numerical estimates. The analytical proof uses `eta_H`.', '',
         '| alpha | A | B | estimated eta_star | sufficient mu_K | computed fold |',
         '|---:|---:|---:|---:|---:|---:|']
for v in r['example2']['rows']:
    lines.append(f"| {v['alpha']:g} | {v['A']:.9e} | {v['B']:.9e} | {v['eta_star']:.6f} | {v['mu_K']:.7f} | {v['mu_fold']:.7f} |")
lines += ['', '## Verified existence bounds', '',
          '| Load | alpha | analytical eta_H | chosen eta | inner radius | outer radius |',
          '|---|---:|---:|---:|---:|---:|',
          f"| exp(u), mu=1 | 1 | {r['constants']['eta_analytical']:.9f} | 0.2 | 0.01 | 75 |",
          '| 10000(1+x)u^2 | 5 | 0.021588272 | 0.02 | 0.72 | 5600 |', '',
          'The small exponential solution has norm below the inner radius of the displayed large-solution annulus.', '',
          '## Computed nonlinear solution norms', '',
          '| Method | resolution | small exponential | large exponential | quadratic |',
          '|---|---:|---:|---:|---:|',
          f"| Green kernel | 48 | {r['example1']['norm_minus']:.9e} | {r['example1']['norm_plus']:.9f} | {r['example3']['norm']:.9f} |"]
for key,label in [('fd','Finite differences'),('fe','Mixed finite elements')]:
    for n,v in r['example1'][key].items():
        lines.append(f"| {label} | {n} | {v['minus']:.9e} | {v['plus']:.9f} | {r['example3'][key][n]:.9f} |")
lines += ['', '## Uniform-load discretization errors', '',
          'Errors are sampled relative maximum errors. Resolution at large alpha can delay the asymptotic regime.', '',
          '| alpha | method | resolution | relative error | observed order |',
          '|---:|---|---:|---:|---:|']
import math
for a,v in r['verification'].items():
    for method in ['fd','fe','gn']:
        previous = None
        for n,e in v[method].items():
            order = ' ' if previous is None else f'{math.log(previous/e,2):.3f}'
            lines.append(f'| {a} | {method.upper()} | {n} | {e:.9e} | {order} |'); previous = e
lines += ['', '## Shear-coefficient comparison', '',
          'Both columns use the same linear shear formula. They are coefficient benchmarks, not separate full models.', '',
          '| L/h | Cowper | k_s=5/6 | gradient h/g=1 | gradient h/g=2 | gradient h/g=5 | gradient h/g=10 |',
          '|---:|---:|---:|---:|---:|---:|---:|']
for v in r['mechanics']['table']:
    keys=['L/h','shear_cowper','shear_5_6','sg_h/g=1','sg_h/g=2','sg_h/g=5','sg_h/g=10']
    lines.append('| '+' | '.join(f'{v[k]:.7f}' for k in keys)+' |')
(ROOT/'docs/RESULTS.md').write_text('\n'.join(lines)+'\n')
print('Wrote docs/RESULTS.md')
